'use strict';

/**
 * Deterministic generator for stress.ts: 500 stylex.create() calls whose
 * values are dominated by CSS shorthands (margin/padding/border/background/
 * font and friends, as plain strings and numbers, no template literals)
 * mixed with typical longhands. The output is committed so the benchmark
 * input is identical on every machine and branch; rerun after changing the
 * pools below:
 *
 *   node packages/benchmarks/ts-compile/fixtures/stress/generate.js
 */

const fs = require('fs');
const path = require('path');

const CREATE_CALLS = 500;

const SHORTHANDS = {
  margin: ['10px 20px', '0 auto', 8, '1rem 2rem 3rem 4rem', 0, '4% 2%'],
  padding: ['10px', '0.5em 1em', 16, '12px 16px 20px', '1px 2px 3px 4px'],
  border: [
    '1px solid red',
    '2px dashed #00f',
    'medium none currentcolor',
    '0.25rem double rgb(1 2 3)',
    'thin solid var(--accent)',
  ],
  background: [
    'red',
    '#fff content-box radial-gradient(crimson, skyblue)',
    'no-repeat url(image.png)',
    'center / contain no-repeat url(foo.svg), #eee 35% url(bar.png)',
    'linear-gradient(to right, red 0%, blue 100%)',
  ],
  font: [
    'italic bold 12px/30px Georgia, serif',
    '14px Arial, sans-serif',
    'small-caps bold 24px/1 sans-serif',
    'caption',
    'normal normal 1.2em/1.5 system-ui',
  ],
  borderRadius: ['4px 8px', '50%', '2px 4px 2px 4px', '10px / 20px'],
  borderWidth: ['1px 2px', 'thin medium thick', 2],
  borderColor: ['red green blue white', 'currentcolor', '#f00 #0f0'],
  outline: ['1px dotted blue', 'thick double #32a1ce', 'none'],
  gap: ['8px 12px', '1rem', 0, '10% 20%'],
  flex: ['1 1 auto', '0 0 50%', 'none', 2],
  inset: ['0 10px 20px 30px', 'auto', 0, '10% auto'],
  textDecoration: ['underline dotted red', 'none', 'overline line-through'],
  transition: [
    'opacity 0.3s ease-in-out',
    'all 0.2s',
    'margin-right 2s ease-in-out 0.5s, color 1s',
  ],
};

const LONGHANDS = {
  color: ['red', '#bada55', 'rgb(10 20 30)'],
  display: ['flex', 'block', 'grid', 'inline-block'],
  position: ['relative', 'absolute', 'static'],
  width: ['100%', 320, 'min-content'],
  height: [240, '50vh', 'auto'],
  fontSize: [12, '1.25rem', 14, 'x-small'],
  lineHeight: [1.5, '20px', 'inherit'],
  marginTop: [4, '0.5rem', 0, 'auto'],
  paddingBottom: [8, '2em'],
  backgroundColor: ['#101010', 'papayawhip', 'transparent'],
  borderTopWidth: [1, '2px', 'thin'],
  overflow: ['hidden', 'auto', 'scroll', 'visible'],
  zIndex: [1, 10, 100],
  opacity: [0.5, 1, 0.25],
};

const SHORTHAND_KEYS = Object.keys(SHORTHANDS);
const LONGHAND_KEYS = Object.keys(LONGHANDS);

const literal = (value) =>
  typeof value === 'string' ? `'${value}'` : String(value);

// Cycles through a different slice of the property pools per call so
// consecutive create() calls see different object shapes, not one shared
// shape that the checker resolves once and caches.
function properties(pools, keys, offset, count) {
  const lines = [];
  for (let i = 0; i < count; i++) {
    const key = keys[(offset + i) % keys.length];
    const pool = pools[key];
    lines.push(`    ${key}: ${literal(pool[(offset + i) % pool.length])},`);
  }
  return lines;
}

function createCall(index) {
  const namespaces = [
    ['root', index, 4, 3],
    ['alt', index + 7, 3, 3],
  ];
  const lines = [`export const styles${index} = stylex.create({`];
  for (const [name, offset, shorthandCount, longhandCount] of namespaces) {
    lines.push(`  ${name}: {`);
    lines.push(
      ...properties(SHORTHANDS, SHORTHAND_KEYS, offset, shorthandCount),
    );
    lines.push(...properties(LONGHANDS, LONGHAND_KEYS, offset, longhandCount));
    lines.push('  },');
  }
  lines.push('});');
  return lines.join('\n');
}

const header = `/**
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 *
 * This source code is licensed under the MIT license found in the
 * LICENSE file in the root directory of this source tree.
 */

/* eslint-disable */

// Generated by generate.js in this directory; do not edit by hand.

import * as stylex from '@stylexjs/stylex';
`;

const calls = [];
for (let index = 0; index < CREATE_CALLS; index++) {
  calls.push(createCall(index));
}

const outPath = path.join(__dirname, 'stress.ts');
fs.writeFileSync(outPath, `${header}\n${calls.join('\n\n')}\n`);
console.log(`Wrote ${CREATE_CALLS} stylex.create() calls to ${outPath}`);
